"""Cursors this server's listings issue, pinned byte for byte, with the SQL each resumes with.

Agents and UIs hold cursors from the running server and pass them back after a deploy, so a
cursor issued today must decode to the same position and resume with the same predicate
under any later paging library. ``golden/paging.txt`` freezes, for every listing this
server declares, one cursor and the strictly-after predicate and ORDER BY it resumes with.

The golden file is frozen output, not generated by the test. A failure means a cursor in
flight would decode differently or resume somewhere else: a breaking change, which needs
explicit sign-off before the golden file is edited.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pytest
from pgkeyset import Listing
from sqlalchemy.dialects.postgresql.asyncpg import PGDialect_asyncpg

from mcp_todos.db.store import _TODOS, _search_listing

GOLDEN = Path(__file__).parent / "golden" / "paging.txt"
# The driver the servers run, so the SQL is what Postgres receives, whatever the default.
_ASYNCPG = PGDialect_asyncpg()
WHEN = datetime(2026, 3, 4, 5, 6, 7, 891011, tzinfo=UTC)

CASES: dict[str, tuple[Listing, tuple[Any, ...]]] = {
    "todos": (_TODOS, (WHEN, "td_01JNQ8X5Z3K7M2P4R6T8V0W2Y4")),
    # A query's listing: its match tier leads, so the query's own words are in the predicate.
    "todos_search": (_search_listing("ship it"), (2, WHEN, "td_01JNQ8X5Z3K7M2P4R6T8V0W2Y4")),
}


def _golden() -> dict[str, tuple[str, str]]:
    cases: dict[str, tuple[str, str]] = {}
    for block in GOLDEN.read_text().split("== ")[1:]:
        name, _, body = block.partition(" ==\n")
        cursor, _, sql = body.rstrip("\n").partition("\n")
        cases[name] = (cursor, sql)
    return cases


def _compiled(clause: Any) -> list[str]:
    compiled = clause.compile(dialect=_ASYNCPG)
    lines = [" ".join(str(compiled).split())]
    return lines + [f"  {k} = {v!r}" for k, v in sorted(compiled.params.items())]


def render(listing: Listing, cursor: str) -> str:
    """The strictly-after predicate a cursor resumes with, and the listing's ORDER BY."""
    lines = ["WHERE", *_compiled(listing.after(listing.decode(cursor)))]
    for sort in listing.order:
        lines += ["ORDER BY", *_compiled(sort.order())]
    return "\n".join(lines)


def test_every_listing_is_frozen() -> None:
    assert set(_golden()) == set(CASES)


@pytest.mark.parametrize("case", sorted(CASES))
def test_a_position_encodes_to_its_frozen_cursor(case: str) -> None:
    listing, key = CASES[case]
    assert listing.encode(key) == _golden()[case][0]


@pytest.mark.parametrize("case", sorted(CASES))
def test_a_frozen_cursor_decodes_to_its_position(case: str) -> None:
    listing, key = CASES[case]
    decoded = listing.decode(_golden()[case][0])
    assert decoded == key
    assert [type(v) for v in decoded] == [type(v) for v in key]
    assert all(v.tzinfo is UTC for v in decoded if isinstance(v, datetime))


@pytest.mark.parametrize("case", sorted(CASES))
def test_a_frozen_cursor_resumes_with_its_frozen_sql(case: str) -> None:
    listing, _ = CASES[case]
    assert render(listing, _golden()[case][0]) == _golden()[case][1]
